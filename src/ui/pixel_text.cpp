void PixelText::rect(int x, int y, int w, int h, float r, float g, float b, int winH)
{
	if (w <= 0 || h <= 0)
		return;
	glScissor(x, winH - y - h, w, h);
	glClearColor(r, g, b, 1.0f);
	glClear(GL_COLOR_BUFFER_BIT);
}

void PixelText::text(const char* str, int x, int y, int scale, float r, float g, float b, int winH)
{
	for (size_t i = 0; i < std::strlen(str); ++i)
	{
		const Glyph* glyph = findGlyph(str[i]);
		if (glyph)
			for (int row = 0; row < 7; ++row)
				for (int col = 0; col < 5; ++col)
					if (glyph->rows[row][col] == '#')
						rect(x + col * scale, y + row * scale, scale, scale, r, g, b, winH);
		x += 6 * scale;
	}
}

int PixelText::textWidth(const char* str, int scale)
{
	int len = static_cast<int>(std::strlen(str));
	return len > 0 ? len * 6 * scale - scale : 0;
}

void PixelText::centered(const char* str, int y, int scale, float r, float g, float b, int winW, int winH)
{
	text(str, (winW - textWidth(str, scale)) / 2, y, scale, r, g, b, winH);
}
